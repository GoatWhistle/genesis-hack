# frozen_string_literal: true

module Rsocket
  # Базовая ошибка инструмента.
  #
  # Всё, что мы показываем пользователю осмысленным сообщением, наследуется
  # отсюда. Так командная строка отличает наши понятные отказы от неожиданных
  # падений: первые печатаются человеку одной строкой, вторые — со следом
  # вызовов, потому что это уже наш баг.
  class Error < StandardError; end

  # Описание API прочитать не удалось: битый YAML, пустой файл, нет
  # обязательных разделов, файл не читается.
  class SpecError < Error
    # Место в файле, где споткнулись. Может быть номером строки или путём
    # внутри описания — что удалось определить.
    attr_reader :where

    def initialize(message, where: nil)
      @where = where
      super(where ? "#{message} (#{where})" : message)
    end
  end

  # Ссылка внутри описания ведёт в никуда или закольцована сама на себя.
  class ReferenceError < SpecError; end

  # Конструкция описания нам известна, но мы её намеренно не поддерживаем.
  #
  # Это не повод останавливать работу: такие случаи складываются в отчёт и
  # показываются человеку в конце прогона. Инструмент, который молча
  # пропускает непонятое, хуже инструмента, который об этом говорит.
  class UnsupportedFeature < Error; end

  # Собрать выходной файл не удалось: шаблон упал, результат не является
  # валидным Ruby, линтер отказался принимать сгенерированный код.
  class GenerationError < Error; end
end
