# frozen_string_literal: true

# Объект операции из системы заказчика.
#
# Откуда взято: пример сгенерированного сервиса в задании обращается к
# `operation.amount`, `operation.id`, `operation.provider_operation_id` и
# `operation.payout_requisite.dig(способ_выплаты, "phone")`. Отсюда и состав
# полей. Имён конкретных провайдеров и их способов выплаты здесь нет
# намеренно: заглушка воспроизводит контракт заказчика, а не чьё-то API.
#
# Имя намеренно не спрятано в пространство имён: у заказчика это модель
# верхнего уровня, и сгенерированный сервис обращается к ней именно так.
# Чтобы этот глобальный `Operation` не всплывал там, где он не нужен,
# `lib/rsocket/runtime.rb` не подключается из `lib/rsocket.rb` — его требует
# только сгенерированный код и проверяльщик.
#
# Struct, а не Data: `provider_operation_id` заполняется уже после создания
# выплаты, то есть объект обязан быть изменяемым.
Operation = Struct.new(
  :id,
  :amount,
  :currency,
  :payout_requisite,
  :provider_operation_id,
  keyword_init: true
) do
  # Реквизиты по умолчанию — пустой хеш, а не nil: сервису удобнее спросить
  # `payout_requisite.dig(...)` и получить nil, чем сначала проверять сам хеш.
  # Валюта по умолчанию не задаётся намеренно: это знание о конкретном
  # провайдере, а в заглушке контракта таких знаний быть не должно.
  def initialize(**attributes)
    super(payout_requisite: {}, **attributes)
  end
end
