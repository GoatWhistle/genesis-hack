# RSOCKET — генератор интеграций с платёжными провайдерами.
#
# На входе: описание API провайдера в формате OpenAPI.
# На выходе: сервис на Ruby по контракту заказчика, инструкция по подключению,
# примеры запросов и ответов, тесты.
#
# Конвейер собран из четырёх независимых частей, каждая живёт в своём каталоге:
#
#   spec/      чтение файла и раскладка в общий вид
#   classify/  определение смысла операций, статусов и ошибок
#   generate/  сборка выходных файлов по шаблонам
#   verify/    проверка результата против поддельного сервера
#
# Ни одна часть не знает названий конкретных провайдеров: всё, что зависит от
# провайдера, живёт в словарях (dictionaries/) и шаблонах (templates/).
module Rsocket
  # Корень репозитория. Нужен, чтобы находить словари и шаблоны независимо от
  # того, откуда запущена команда.
  def self.root
    @root ||= File.expand_path("..", __dir__)
  end
end
